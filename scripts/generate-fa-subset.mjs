// Generates src/assets/fontawesome-subset.css: Font Awesome base rules plus
// ONLY the icons actually referenced in src/. The full all.min.css defines
// ~1900 icons (~100KB of mostly-unused CSS, PageSpeed's "reduce unused CSS"
// flag); the site uses ~90.
//
//   npm run generate:fa-subset
//
// Rerun after adding or removing any fa-* icon anywhere in src/ — the CSS for
// a new icon won't exist until you do (the icon renders as an empty box).
// Icon classes must appear as literal `fa-name` tokens; the scan cannot see
// dynamically concatenated class names.
import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const faDir = path.join(root, "node_modules", "@fortawesome", "fontawesome-free");
const outFile = path.join(root, "src", "assets", "fontawesome-subset.css");

// Style/utility classes that are part of the base rules below, not icons.
const NON_ICON = new Set(["fa-solid", "fa-regular", "fa-brands", "fa-spin"]);

// --- collect fa-* tokens from the source tree ---
const tokens = new Set();
const walk = (dir) => {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, entry.name);
		if (entry.isDirectory()) walk(p);
		else if (/\.(vue|ts|json|html)$/.test(entry.name)) {
			for (const m of fs.readFileSync(p, "utf8").matchAll(/\bfa-[a-z0-9-]+\b/g)) {
				tokens.add(m[0]);
			}
		}
	}
};
walk(path.join(root, "src"));

// --- resolve tokens to codepoints (canonical names + aliases) ---
const meta = JSON.parse(fs.readFileSync(path.join(faDir, "metadata", "icon-families.json"), "utf8"));
const unicodeByName = new Map();
for (const [name, entry] of Object.entries(meta)) {
	unicodeByName.set(name, entry.unicode);
	for (const alias of entry.aliases?.names ?? []) unicodeByName.set(alias, entry.unicode);
}

const icons = [];
const unknown = [];
for (const token of [...tokens].sort()) {
	if (NON_ICON.has(token)) continue;
	const unicode = unicodeByName.get(token.slice(3));
	if (unicode) icons.push({ token, unicode });
	else unknown.push(token);
}
if (unknown.length) {
	console.error(
		`Unrecognized fa-* classes: ${unknown.join(", ")}\n` +
			"If these are new Font Awesome utility classes (like fa-spin), add them to NON_ICON\n" +
			"and port their rules into the template below; if they are icons, the metadata lookup failed.",
	);
	process.exit(1);
}

// --- emit ---
const css = `/* GENERATED by scripts/generate-fa-subset.mjs — do not edit by hand.
 * Rerun \`npm run generate:fa-subset\` after adding/removing fa-* icons in src/.
 * Base rules mirror @fortawesome/fontawesome-free/css/all.css (v6, free styles),
 * with font-display: swap (PageSpeed "font-display" flag). */

@font-face {
	font-family: "Font Awesome 6 Free";
	font-style: normal;
	font-weight: 900;
	font-display: swap;
	src: url("../../node_modules/@fortawesome/fontawesome-free/webfonts/fa-solid-900.woff2") format("woff2");
}
@font-face {
	font-family: "Font Awesome 6 Free";
	font-style: normal;
	font-weight: 400;
	font-display: swap;
	src: url("../../node_modules/@fortawesome/fontawesome-free/webfonts/fa-regular-400.woff2") format("woff2");
}
@font-face {
	font-family: "Font Awesome 6 Brands";
	font-style: normal;
	font-weight: 400;
	font-display: swap;
	src: url("../../node_modules/@fortawesome/fontawesome-free/webfonts/fa-brands-400.woff2") format("woff2");
}

.fa-solid,
.fa-regular,
.fa-brands {
	-moz-osx-font-smoothing: grayscale;
	-webkit-font-smoothing: antialiased;
	display: var(--fa-display, inline-block);
	font-style: normal;
	font-variant: normal;
	line-height: 1;
	text-rendering: auto;
}
.fa-solid,
.fa-regular {
	font-family: "Font Awesome 6 Free";
}
.fa-solid {
	font-weight: 900;
}
.fa-regular {
	font-weight: 400;
}
.fa-brands {
	font-family: "Font Awesome 6 Brands";
	font-weight: 400;
}

.fa-spin {
	animation: fa-spin 2s linear infinite;
}
@keyframes fa-spin {
	0% {
		transform: rotate(0deg);
	}
	100% {
		transform: rotate(360deg);
	}
}

${icons.map(({ token, unicode }) => `.${token}::before {\n\tcontent: "\\${unicode}";\n}`).join("\n")}
`;

fs.writeFileSync(outFile, css);
console.log(`Wrote ${path.relative(root, outFile)}: ${icons.length} icons from ${tokens.size} fa-* tokens.`);
